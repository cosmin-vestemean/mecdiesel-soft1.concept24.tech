    RUNID INT NOT NULL IDENTITY(1,1) PRIMARY KEY,
    COMPANY SMALLINT NOT NULL,
    AZI DATE NULL,
    FAZA VARCHAR(20) NOT NULL DEFAULT 'CLASSIFY',
    STATUS VARCHAR(10) NOT NULL DEFAULT 'RUNNING',
    MTRL INT NULL,
    NR_RANDURI INT NULL,
    DURATA_SEC INT NULL,
