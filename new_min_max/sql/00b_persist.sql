    ERRORMSG NVARCHAR(500) NULL,
    STARTEDAT DATETIME NOT NULL DEFAULT GETDATE(),
    FINISHEDAT DATETIME NULL,
    CREATEDBY INT NULL,
    COMPUTE_STATUS VARCHAR(10) NULL,
    COMPUTE_STARTEDAT DATETIME NULL,
    COMPUTE_FINISHEDAT DATETIME NULL,
    COMPUTE_DURATA_SEC INT NULL,
